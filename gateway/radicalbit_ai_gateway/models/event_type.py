from enum import Enum


class EventType(str, Enum):
    MODEL_INVOCATION = 'MODEL_INVOCATION'
    FALLBACK = 'FALLBACK'
    GUARDRAIL = 'GUARDRAIL'
    ROUTING = 'ROUTING'
    RATE_LIMIT = 'RATE_LIMIT'
    CACHE_HIT = 'CACHE_HIT'
    TOKEN_INPUT_LIMIT = 'TOKEN_INPUT_LIMIT'
    TOKEN_OUTPUT_LIMIT = 'TOKEN_OUTPUT_LIMIT'
    AUDIO_DURATION_LIMIT = 'AUDIO_DURATION_LIMIT'
    BUDGET_LIMIT = 'BUDGET_LIMIT'
    CREDENTIAL_RATE_LIMIT = 'CREDENTIAL_RATE_LIMIT'
    CREDENTIAL_TOKEN_INPUT_LIMIT = 'CREDENTIAL_TOKEN_INPUT_LIMIT'
    CREDENTIAL_TOKEN_OUTPUT_LIMIT = 'CREDENTIAL_TOKEN_OUTPUT_LIMIT'
    CREDENTIAL_BUDGET_LIMIT = 'CREDENTIAL_BUDGET_LIMIT'
    PROJECT_BUDGET_LIMIT = 'PROJECT_BUDGET_LIMIT'
    LIMIT_THRESHOLD = 'LIMIT_THRESHOLD'
    INPUT_TOKEN_PROCESSED = 'INPUT_TOKEN_PROCESSED'
    OUTPUT_TOKEN_PROCESSED = 'OUTPUT_TOKEN_PROCESSED'
    CACHE_INPUT_TOKENS = 'CACHE_INPUT_TOKENS'
    CACHE_OUTPUT_TOKENS = 'CACHE_OUTPUT_TOKENS'
    MCP_INVOCATION = 'MCP_INVOCATION'
    REQUEST = 'REQUEST'


# The events a limit leaves when it blocks a request: route, credential or
# project; rate, token, duration or budget. LIMIT_THRESHOLD is only a warning.
LIMIT_BLOCK_EVENT_TYPES: tuple[str, ...] = tuple(
    t.value for t in EventType if t.value.endswith('_LIMIT')
)

# The events that count the tokens a request consumed, judges included.
# Tokens and cost of a request are summed over these.
PROCESSED_TOKEN_EVENT_TYPES: tuple[str, ...] = (
    EventType.INPUT_TOKEN_PROCESSED.value,
    EventType.OUTPUT_TOKEN_PROCESSED.value,
)
